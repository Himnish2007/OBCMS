let currentLang = localStorage.getItem("himnish_lang") || "en";

// t(key, vars?) — looks up the key in the active language (falling back to
// English, then to the key itself so a missing translation never renders
// blank). vars lets callers substitute {placeholders} for dynamic values.
function t(key, vars) {
  const dict = I18N[currentLang] || I18N.en;
  let str = dict[key] !== undefined ? dict[key] : (I18N.en[key] !== undefined ? I18N.en[key] : key);
  if (vars) {
    Object.keys(vars).forEach((k) => { str = str.replace(`{${k}}`, vars[k]); });
  }
  return str;
}

function translateStaticDom() {
  document.documentElement.lang = currentLang === "hi" ? "hi" : "en";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === currentLang);
  });
}

// Called on load and whenever the language toggle is used. Re-renders the
// currently active view too, so JS-generated tables/cards pick up the new
// language immediately (their render functions call t() internally).
function applyLanguage(lang) {
  currentLang = lang === "hi" ? "hi" : "en";
  localStorage.setItem("himnish_lang", currentLang);
  translateStaticDom();
  if (typeof refreshCurrentView === "function") {
    try { refreshCurrentView(); } catch (err) { /* app.js may not be booted yet */ }
  }
}

document.addEventListener("DOMContentLoaded", () => {
  translateStaticDom();
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => applyLanguage(btn.dataset.lang));
  });
});
